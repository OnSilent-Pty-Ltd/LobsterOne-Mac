import AppKit
import ApplicationServices
import Carbon.HIToolbox
import CoreGraphics

enum PasteOutcome: Equatable {
    case pasted
    case copied(reason: CopiedReason)   // text left on the clipboard for a manual ⌘V
    enum CopiedReason { case noAccessibility, secureInput, postFailed }
}

/// Puts dictated text into whatever field has focus by way of the clipboard and a synthetic ⌘V,
/// then puts the person's clipboard back. Typing the text key by key would be slower, trip over
/// keyboard layouts and autocorrect, and terminals handle a paste far better than a burst of keys.
///
/// When pasting can't work (no Accessibility grant, or Secure Keyboard Entry is on, which drops
/// synthetic keys without telling anyone) the text is left on the clipboard as an ordinary copy
/// so it is one ⌘V away.
@MainActor
enum TextPaster {
    /// Stamped on our synthetic key events so the dictation hotkey can tell them from real ones.
    nonisolated static let syntheticEventMarker: Int64 = 0x4C4F_4253 // "LOBS"

    /// How long to leave the text on the clipboard before restoring. Terminals and Electron
    /// apps read the pasteboard some time after the ⌘V arrives; 0.9 s is what shipping apps use.
    nonisolated static let restoreDelay: Duration = .milliseconds(900)
    /// The trigger is a modifier, so wait for the person to let go of it; an Option still held
    /// would turn ⌘V into ⌥⌘V.
    nonisolated static let modifierReleaseTimeout: Duration = .milliseconds(600)

    // Types clipboard managers recognise as "don't record this" (nspasteboard.org).
    nonisolated static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    nonisolated static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    nonisolated static let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")

    /// Every item on a pasteboard with every type's data, so images, file URLs and rich text
    /// come back exactly as they were.
    struct Snapshot: Equatable {
        var items: [[NSPasteboard.PasteboardType: Data]]
    }

    /// The clipboard we owe the person, while a restore is still waiting.
    private struct PendingRestore {
        let snapshot: Snapshot
        let changeCount: Int
        let pasteboard: NSPasteboard
        let task: Task<Void, Never>
    }
    private static var pending: PendingRestore?

    static func paste(_ text: String) async -> PasteOutcome {
        await paste(text, pasteboard: .general)
    }

    static func paste(_ text: String, pasteboard: NSPasteboard) async -> PasteOutcome {
        if !AXIsProcessTrusted() { return leaveCopied(text, on: pasteboard, reason: .noAccessibility) }
        if IsSecureEventInputEnabled() { return leaveCopied(text, on: pasteboard, reason: .secureInput) }

        // Two pastes in quick succession: the clipboard now holds the first one's text, and the
        // one to put back is still the person's original.
        let original: Snapshot
        if let pending, pending.pasteboard == pasteboard, pending.changeCount == pasteboard.changeCount {
            pending.task.cancel()
            original = pending.snapshot
        } else {
            original = snapshot(of: pasteboard)
        }
        pending?.task.cancel()
        pending = nil

        let written = writeTransient(text, to: pasteboard)
        await waitForModifiersReleased()
        try? await Task.sleep(for: .milliseconds(50))

        guard await postCommandV() else {
            // Nothing was pasted; leave the text as a plain copy the person can paste themselves.
            DebugLog.shared.log("Dictation paste: couldn't create key events, left text on the clipboard")
            return leaveCopied(text, on: pasteboard, reason: .postFailed)
        }

        let task = Task { @MainActor in
            try? await Task.sleep(for: restoreDelay)
            guard !Task.isCancelled else { return }
            if !restoreIfUnchanged(original, expectedChangeCount: written, on: pasteboard) {
                DebugLog.shared.log("Dictation paste: clipboard changed since the paste, left it alone")
            }
            pending = nil
        }
        pending = PendingRestore(snapshot: original, changeCount: written, pasteboard: pasteboard, task: task)
        return .pasted
    }

    // MARK: Pasteboard

    static func snapshot(of pasteboard: NSPasteboard) -> Snapshot {
        let items = (pasteboard.pasteboardItems ?? []).map { item in
            var types: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { types[type] = data }
            }
            return types
        }
        return Snapshot(items: items)
    }

    static func restore(_ snapshot: Snapshot, to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        let items = snapshot.items.map { types in
            let item = NSPasteboardItem()
            for (type, data) in types { item.setData(data, forType: type) }
            return item
        }
        if !items.isEmpty { pasteboard.writeObjects(items) }
    }

    /// Puts the snapshot back only if nothing else has written to the pasteboard since our
    /// write. If the person copied something in the meantime, that copy wins.
    @discardableResult
    static func restoreIfUnchanged(_ snapshot: Snapshot, expectedChangeCount: Int, on pasteboard: NSPasteboard) -> Bool {
        guard pasteboard.changeCount == expectedChangeCount else { return false }
        restore(snapshot, to: pasteboard)
        return true
    }

    /// Writes the text marked as transient so clipboard managers skip it. Returns the change
    /// count right after the write, which is how a later restore knows the text is still ours.
    static func writeTransient(_ text: String, to pasteboard: NSPasteboard) -> Int {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: transientType)
        item.setData(Data(), forType: autoGeneratedType)
        item.setString(Bundle.main.bundleIdentifier ?? "com.lobsterone.mac", forType: sourceType)
        pasteboard.writeObjects([item])
        return pasteboard.changeCount
    }

    /// A plain copy, the same as ⌘C would make. Left in place for good, so no markers: the
    /// person may want it in their clipboard history.
    static func writeCopy(_ text: String, to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }

    private static func leaveCopied(_ text: String, on pasteboard: NSPasteboard, reason: PasteOutcome.CopiedReason) -> PasteOutcome {
        pending?.task.cancel()
        pending = nil
        writeCopy(text, to: pasteboard)
        return .copied(reason: reason)
    }

    // MARK: Keys

    private static func waitForModifiersReleased() async {
        let held: CGEventFlags = [.maskCommand, .maskAlternate, .maskControl, .maskShift, .maskSecondaryFn]
        let clock = ContinuousClock()
        let deadline = clock.now + modifierReleaseTimeout
        while clock.now < deadline {
            if CGEventSource.flagsState(.combinedSessionState).rawValue & held.rawValue == 0 { return }
            try? await Task.sleep(for: .milliseconds(10))
        }
    }

    /// Command down, V down, V up, Command up, 10 ms apart. Electron apps ignore a V that only
    /// carries the Command flag; they want to see the Command key itself go down.
    /// A private event source keeps the person's real modifier state out of our events.
    private static func postCommandV() async -> Bool {
        guard let source = CGEventSource(stateID: .privateState) else { return false }
        let commandKey = CGKeyCode(kVK_Command)
        let vKey = commandVKeyCode()
        // Command plus the device bit for the left Command key (NX_DEVICELCMDKEYMASK).
        let commandFlags = CGEventFlags(rawValue: CGEventFlags.maskCommand.rawValue | 0x8)

        let steps: [(CGKeyCode, Bool, CGEventFlags)] = [
            (commandKey, true, commandFlags),
            (vKey, true, commandFlags),
            (vKey, false, commandFlags),
            (commandKey, false, []),
        ]
        var events: [CGEvent] = []
        for (key, down, flags) in steps {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: down) else { return false }
            event.flags = flags
            event.setIntegerValueField(.eventSourceUserData, value: syntheticEventMarker)
            events.append(event)
        }
        for (index, event) in events.enumerated() {
            if index > 0 { try? await Task.sleep(for: .milliseconds(10)) }
            event.post(tap: .cghidEventTap)
        }
        return true
    }

    /// The key that types "v" with Command held in the current layout. Hard-coding the ANSI
    /// keycode 9 pastes nothing on Dvorak or Neo. Command is part of the lookup because many
    /// non-Latin layouts switch to their Latin keys while Command is down.
    static func commandVKeyCode() -> CGKeyCode {
        let fallback = CGKeyCode(kVK_ANSI_V)
        guard let source = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue(),
              let property = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData)
        else { return fallback }
        let layoutData = Unmanaged<CFData>.fromOpaque(property).takeUnretainedValue()
        guard let bytes = CFDataGetBytePtr(layoutData) else { return fallback }

        return bytes.withMemoryRebound(to: UCKeyboardLayout.self, capacity: 1) { layout in
            // UCKeyTranslate wants Carbon modifier bits shifted right by 8.
            let commandState = UInt32((cmdKey >> 8) & 0xFF)
            let keyboardType = UInt32(LMGetKbdType())
            for keyCode in UInt16(0)...127 {
                var deadKeyState: UInt32 = 0
                var chars = [UniChar](repeating: 0, count: 4)
                var length = 0
                let status = UCKeyTranslate(layout, keyCode, UInt16(kUCKeyActionDisplay), commandState,
                                            keyboardType, OptionBits(kUCKeyTranslateNoDeadKeysMask),
                                            &deadKeyState, chars.count, &length, &chars)
                if status == noErr, length == 1, chars[0] == UniChar(UInt8(ascii: "v")) {
                    return CGKeyCode(keyCode)
                }
            }
            return fallback
        }
    }
}
