import AppKit
import Testing
@testable import LobsterOne

// Every test uses its own named pasteboard, never the general one, and none posts key events.
@MainActor
private func scratchPasteboard() -> NSPasteboard {
    NSPasteboard(name: NSPasteboard.Name("com.lobsterone.tests.\(UUID().uuidString)"))
}

private let pngType = NSPasteboard.PasteboardType.png
private let pngBytes = Data([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x01, 0x02])

/// Two items: rich text with a plain fallback, and a file URL next to image data.
@MainActor
private func fillWithMixedContent(_ pb: NSPasteboard) {
    pb.clearContents()
    let text = NSPasteboardItem()
    text.setString("original", forType: .string)
    text.setData(Data("{\\rtf1 original}".utf8), forType: .rtf)
    let file = NSPasteboardItem()
    file.setString("file:///tmp/example.png", forType: .fileURL)
    file.setData(pngBytes, forType: pngType)
    pb.writeObjects([text, file])
}

@MainActor @Test func textPasterSnapshotRestoreRoundTripKeepsEveryItemAndType() {
    let pb = scratchPasteboard()
    defer { pb.releaseGlobally() }
    fillWithMixedContent(pb)
    let before = TextPaster.snapshot(of: pb)
    #expect(before.items.count == 2)

    _ = TextPaster.writeTransient("dictated", to: pb)
    #expect(pb.string(forType: .string) == "dictated")

    TextPaster.restore(before, to: pb)
    #expect(TextPaster.snapshot(of: pb) == before)
    let items = pb.pasteboardItems ?? []
    #expect(items.count == 2)
    #expect(items.first?.string(forType: .string) == "original")
    #expect(items.first?.data(forType: .rtf) == Data("{\\rtf1 original}".utf8))
    #expect(items.last?.string(forType: .fileURL) == "file:///tmp/example.png")
    #expect(items.last?.data(forType: pngType) == pngBytes)
}

@MainActor @Test func textPasterRestoresAnEmptyClipboardAsEmpty() {
    let pb = scratchPasteboard()
    defer { pb.releaseGlobally() }
    pb.clearContents()
    let empty = TextPaster.snapshot(of: pb)
    let written = TextPaster.writeTransient("dictated", to: pb)
    #expect(TextPaster.restoreIfUnchanged(empty, expectedChangeCount: written, on: pb))
    #expect((pb.pasteboardItems ?? []).isEmpty)
}

@MainActor @Test func textPasterMarksItsWriteTransient() throws {
    let pb = scratchPasteboard()
    defer { pb.releaseGlobally() }
    let written = TextPaster.writeTransient("dictated", to: pb)
    #expect(written == pb.changeCount)
    let item = try #require(pb.pasteboardItems?.first)
    #expect(item.string(forType: .string) == "dictated")
    #expect(item.types.contains(TextPaster.transientType))
    #expect(item.types.contains(TextPaster.autoGeneratedType))
    #expect(item.string(forType: TextPaster.sourceType)?.isEmpty == false)
}

@MainActor @Test func textPasterPlainCopyHasNoMarkers() {
    let pb = scratchPasteboard()
    defer { pb.releaseGlobally() }
    TextPaster.writeCopy("dictated", to: pb)
    #expect(pb.pasteboardItems?.count == 1)
    let types = pb.pasteboardItems?.first?.types ?? []
    #expect(pb.string(forType: .string) == "dictated")
    #expect(!types.contains(TextPaster.transientType))
    #expect(!types.contains(TextPaster.autoGeneratedType))
    #expect(!types.contains(TextPaster.sourceType))
}

@MainActor @Test func textPasterSkipsRestoreWhenClipboardChanged() {
    let pb = scratchPasteboard()
    defer { pb.releaseGlobally() }
    fillWithMixedContent(pb)
    let before = TextPaster.snapshot(of: pb)
    let written = TextPaster.writeTransient("dictated", to: pb)

    // The person copies something else before the restore runs.
    pb.clearContents()
    pb.setString("copied meanwhile", forType: .string)

    #expect(!TextPaster.restoreIfUnchanged(before, expectedChangeCount: written, on: pb))
    #expect(pb.string(forType: .string) == "copied meanwhile")
}

@MainActor @Test func textPasterRestoresWhenClipboardUnchanged() {
    let pb = scratchPasteboard()
    defer { pb.releaseGlobally() }
    fillWithMixedContent(pb)
    let before = TextPaster.snapshot(of: pb)
    let written = TextPaster.writeTransient("dictated", to: pb)
    #expect(TextPaster.restoreIfUnchanged(before, expectedChangeCount: written, on: pb))
    #expect(TextPaster.snapshot(of: pb) == before)
}

@MainActor @Test func textPasterFindsAKeyForV() {
    // Whatever layout the machine has, the lookup lands on a real keycode (ANSI V is 9).
    let code = TextPaster.commandVKeyCode()
    #expect(code <= 127)
}
